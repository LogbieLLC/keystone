#!/usr/bin/env bash
# Enforces the code-safety boundaries of PRD SEC-18 / SECURITY.md SECP-06:
#   1. `unsafe` code exists only in keystone-core/src/crypto/ffi.rs.
#   2. Every other Rust source file has #![forbid(unsafe_code)]. Exempt: the parents
#      of ffi.rs, because `forbid` cannot be relaxed for a child module. The crate root
#      keystone-core/src/lib.rs must #![deny(unsafe_code)] instead, and
#      crypto/mod.rs may hold only module declarations and re-exports.
#      No other attribute may name the `unsafe_code` lint (allow, expect, warn, an
#      item-level deny or forbid, cfg_attr): the only ones allowed are
#      #![forbid(unsafe_code)], #![deny(unsafe_code)] in the crate root and the one
#      #[allow(unsafe_code)] on `mod ffi;` in crypto/mod.rs.
#   3. OpenSSL is reachable only inside keystone-core/src/crypto/:
#      - no Rust file outside it names the `openssl` or `openssl_sys` crate in any
#        form (`openssl::`, `::openssl::`, `use openssl as x`, `extern crate openssl`,
#        `openssl_sys`, `openssl-sys`);
#      - no file inside it re-exports them (`pub use`, `pub type`);
#      - only the workspace root and keystone-core/Cargo.toml depend on them, and
#        no manifest renames them (`package = "openssl"`).
#   4. No networking API is used anywhere (PRD HR-1, SEC-03, SECP-07).
#
# Rules 1 to 3 are checked on the code with comments, string literals and character
# literals blanked out (line numbers kept), so `/* x */ unsafe {` is found while a
# comment or an error message that mentions `unsafe` or `openssl` is not a violation.
#
# This is a text check, not a compiler rule: code generated by a macro from another
# crate is not seen. Moving crypto/ into its own crate, the only one that depends on
# OpenSSL, with #![forbid(unsafe_code)] at the root of keystone-core, would make the
# boundary a compile error (needs the maintainer's approval: it adds a crate).
# Exit code 0 = all rules hold.
set -euo pipefail
cd "$(dirname "$0")/.."

FFI="keystone-core/src/crypto/ffi.rs"
CRYPTO_DIR="keystone-core/src/crypto/"
CRYPTO_MOD="keystone-core/src/crypto/mod.rs"
CORE_ROOT="keystone-core/src/lib.rs"
CORE_MANIFEST="keystone-core/Cargo.toml"
failures=0
fail() { echo "BOUNDARY VIOLATION: $*" >&2; failures=$((failures + 1)); }

# Writes a copy of each Rust file given on the command line to "$1/<path>", with
# every comment (line, block, nested block, doc), string literal (plain, byte, C,
# raw) and character literal replaced by spaces. Newlines are kept, so line numbers
# stay the same. Lifetimes and labels ('a) are code and stay.
read -r -d '' STRIP_RUST <<'PERL' || true
use strict; use warnings;
my $dest = shift @ARGV;
my $ident = qr/[A-Za-z0-9_]/;
sub blank { (my $t = $_[0]) =~ s/[^\n]/ /g; return $t }
for my $path (@ARGV) {
    my $s = do { local $/; open(my $in, '<:encoding(UTF-8)', $path) or die "$path: $!"; <$in> };
    my ($n, $i, $out) = (length $s, 0, '');
    while ($i < $n) {
        pos($s) = $i;
        if ($s =~ /\G([^\/"'rbc]+)/gc) { $out .= $1; $i = pos($s); next }
        my $prev = $i > 0 ? substr($s, $i - 1, 1) : ' ';
        my $j;
        if ($s =~ /\G\/\//gc) {
            $j = index($s, "\n", $i); $j = $n if $j < 0;
        } elsif ($s =~ /\G\/\*/gc) {
            my $depth = 1; $j = $i + 2;
            while ($j < $n && $depth > 0) {
                my $t = substr($s, $j, 2);
                if ($t eq '/*') { $depth++; $j += 2 } elsif ($t eq '*/') { $depth--; $j += 2 } else { $j++ }
            }
        } elsif ($prev !~ $ident && $s =~ /\G[bc]?r(#*)"/gc) {
            my $close = '"' . $1; $j = index($s, $close, pos($s));
            $j = $j < 0 ? $n : $j + length $close;
        } elsif ($s =~ /\G"/gc || ($prev !~ $ident && $s =~ /\G[bc]"/gc)) {
            $j = pos($s);
            while ($j < $n) {
                my $ch = substr($s, $j, 1);
                if ($ch eq '\\') { $j += 2 } elsif ($ch eq '"') { $j++; last } else { $j++ }
            }
            $j = $n if $j > $n;
        } elsif ($s =~ /\G'(?:\\(?:u\{[0-9A-Fa-f_]*\}|x[0-9A-Fa-f]{2}|.)|[^\\'\n])'/gc
                 || ($prev !~ $ident && $s =~ /\Gb'(?:\\(?:x[0-9A-Fa-f]{2}|.)|[^\\'\n])'/gc)) {
            $j = pos($s);
        } else {
            $out .= substr($s, $i, 1); $i++; next;
        }
        $out .= blank(substr($s, $i, $j - $i)); $i = $j;
    }
    my $target = "$dest/$path";
    (my $dir = $target) =~ s{/[^/]*$}{};
    system('mkdir', '-p', $dir) == 0 or die "mkdir $dir";
    open(my $outf, '>:encoding(UTF-8)', $target) or die "$target: $!";
    print $outf $out;
    close $outf;
}
PERL

mapfile -t sources < <(git ls-files --cached --others --exclude-standard -- '*.rs' | sort)
existing=()
for file in "${sources[@]}"; do
  [[ -f "$file" ]] && existing+=("$file")
done
CODE="$(mktemp -d)"
trap 'rm -rf "$CODE"' EXIT
perl -e "$STRIP_RUST" "$CODE" "${existing[@]}"

# Lines of the code-only copy of $1 matching the extended regex $2 ("line:text").
code_grep() { grep -nE -- "$2" "$CODE/$1" || true; }

for file in "${existing[@]}"; do
  # Rule 1: no `unsafe` keyword outside the FFI module.
  if [[ "$file" != "$FFI" ]]; then
    hits=$(code_grep "$file" '\bunsafe\b')
    [[ -z "$hits" ]] || fail "$file uses 'unsafe' outside $FFI (line ${hits%%:*})"
  fi
  # Rule 2: #![forbid(unsafe_code)] in every file except ffi.rs and its two parents
  # (crypto/mod.rs and the crate root, which instead denies unsafe_code crate-wide).
  if [[ "$file" == "$CORE_ROOT" ]]; then
    [[ -n "$(code_grep "$file" '^#!\[deny\(unsafe_code\)\]\s*$')" ]] \
      || fail "$file must deny unsafe_code crate-wide"
  elif [[ "$file" != "$FFI" && "$file" != "$CRYPTO_MOD" ]]; then
    [[ -n "$(code_grep "$file" '^#!\[forbid\(unsafe_code\)\]\s*$')" ]] \
      || fail "$file is missing #![forbid(unsafe_code)]"
  fi
  # Rule 2: no other attribute names the unsafe_code lint.
  allowed='^[0-9]+:\s*#!\[forbid\(unsafe_code\)\]\s*$'
  if [[ "$file" == "$CORE_ROOT" ]]; then
    allowed="$allowed|^[0-9]+:\\s*#!\\[deny\\(unsafe_code\\)\\]\\s*\$"
  elif [[ "$file" == "$CRYPTO_MOD" ]]; then
    allowed="$allowed|^[0-9]+:\\s*#\\[allow\\(unsafe_code\\)\\]\\s*\$"
  fi
  hits=$(code_grep "$file" '\bunsafe_code\b' | grep -vE "$allowed" || true)
  [[ -z "$hits" ]] || fail "$file names the unsafe_code lint in an attribute that is not allowed (line ${hits%%:*})"
  # Rule 3: OpenSSL only inside the crypto module, and never re-exported from it.
  if [[ "$file" != "$CRYPTO_DIR"* ]]; then
    hits=$(code_grep "$file" '\bopenssl(_sys)?\b')
    [[ -z "$hits" ]] || fail "$file names the OpenSSL crate outside $CRYPTO_DIR (line ${hits%%:*})"
  else
    hits=$(code_grep "$file" '\bpub\b[^;]*\b(use|type)\b[^;]*\b(openssl|openssl_sys|sys)\b')
    [[ -z "$hits" ]] || fail "$file re-exports OpenSSL from $CRYPTO_DIR (line ${hits%%:*})"
  fi
  # Rule 4: no networking APIs.
  if grep -nE '\bstd::net\b|\bTcpStream\b|\bUdpSocket\b|\bTcpListener\b|rustix::net\b' "$file" >/dev/null; then
    fail "$file uses a networking API (HR-1)"
  fi
done

# Rule 3: only the workspace root and keystone-core depend on openssl / openssl-sys,
# and no manifest renames them.
mapfile -t manifests < <(git ls-files --cached --others --exclude-standard -- 'Cargo.toml' '*/Cargo.toml' | sort)
for manifest in "${manifests[@]}"; do
  [[ -f "$manifest" ]] || continue
  if grep -nE 'package\s*=\s*"openssl(-sys)?"' "$manifest" >/dev/null; then
    fail "$manifest renames the openssl crate; depend on it under its own name in $CORE_MANIFEST only"
  fi
  if [[ "$manifest" != "Cargo.toml" && "$manifest" != "$CORE_MANIFEST" ]] \
    && grep -nE '^\s*"?openssl(-sys|_sys)?"?\s*(\.|=)|^\s*\[(.*\.)?dependencies\.openssl(-sys)?\]' "$manifest" >/dev/null; then
    fail "$manifest depends on OpenSSL; only $CORE_MANIFEST may"
  fi
done

# crypto/mod.rs may contain only comments, attributes, mod and use lines.
if grep -nvE '^\s*$|^\s*#\[allow\(unsafe_code\)\]\s*$|^\s*(pub(\(crate\))? )?mod [a-z_0-9]+;\s*$|^\s*pub use [^;]+;\s*$' "$CODE/$CRYPTO_MOD" >/dev/null; then
  fail "$CRYPTO_MOD must contain only module declarations and re-exports"
fi
# Only the ffi declaration may carry the allow attribute.
if [[ $(grep -cE '\bunsafe_code\b' "$CODE/$CRYPTO_MOD") -ne 1 ]] \
  || ! grep -A1 -E '^\s*#\[allow\(unsafe_code\)\]\s*$' "$CODE/$CRYPTO_MOD" | grep -qE '^\s*mod ffi;\s*$'; then
  fail "$CRYPTO_MOD must allow unsafe_code exactly once, on 'mod ffi;'"
fi
# Each unsafe block, unsafe impl and unsafe extern block in the FFI module needs a
# SAFETY comment just above it: in the 3 lines above, or in the run of `//` comment
# lines that ends right above it. Blocks are found in the code-only copy, so one
# after a block comment (`/* x */ unsafe {`) or inside an argument list is found too.
if [[ -f "$FFI" ]]; then
  while IFS=: read -r line _; do
    start=$((line > 3 ? line - 3 : 1))
    while ((start > 1)) && sed -n "$((start - 1))p" "$FFI" | grep -qE '^\s*//'; do
      start=$((start - 1))
    done
    if ! sed -n "${start},${line}p" "$FFI" | grep -q 'SAFETY:'; then
      fail "$FFI:$line unsafe block without a // SAFETY: comment just above it"
    fi
  done < <(grep -nE '\bunsafe\s*(\{|impl\b|extern\s*(\{|$))' "$CODE/$FFI" || true)
fi

if [[ $failures -gt 0 ]]; then
  echo "$failures boundary violation(s)." >&2
  exit 1
fi
echo "Boundaries OK: unsafe only in $FFI, OpenSSL only in keystone-core/src/crypto/, no networking APIs."
