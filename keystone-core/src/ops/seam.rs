//! Internal hooks for the test seams in [`super::testing`] (FR-22 AC6, AC7).
//!
//! Every function here is a no-op in a `production` build: it never fails, never
//! supplies a key and never supplies a serial. The state behind the hooks exists only
//! in non-production builds and is thread-local, so a test arms it for the operation it
//! runs on its own thread.
#![forbid(unsafe_code)]

use crate::crypto::{CancelFlag, CryptoError, RsaPrivateKey, generate_rsa};
use crate::model::Serial;
use crate::store::YubikeySetupStep;

use super::OpsError;
use super::progress::{Progress, ProgressSink};

/// A named point in an operation where a test can simulate a crash (FR-22 AC6, AC7).
///
/// When an armed point is reached the operation stops at once with
/// [`OpsError::InjectedFault`], exactly as if the process had died there: nothing is
/// cleaned up and the journal is left as it is, so recovery after a "restart" can be
/// tested.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum FaultPoint {
    /// The pending entry is written; the first signature has not been made.
    BeforeSigning,
    /// A certificate or CRL was signed but not yet journaled (the signature exists only
    /// in memory).
    AfterSigning,
    /// A signed certificate or CRL was journaled on every drive.
    AfterSignedRecorded,
    /// A YubiKey setup step took effect on the token but is not journaled yet.
    AfterTokenStep(YubikeySetupStep),
    /// A YubiKey setup step was journaled on every drive.
    AfterTokenStepRecorded(YubikeySetupStep),
    /// Every output is staged and the `staged` entry is written.
    AfterStaged,
    /// Every output was moved into place on every drive.
    AfterCommit,
    /// The audit entries were written; the `completed` entry was not.
    AfterAudit,
    /// The `completed` entry was written; nothing was exported yet.
    BeforeExport,
}

/// RSA key material: a key generated by this operation, or (only in non-production
/// builds, for tests) a cached synthetic key supplied by `keystone-testkit`.
pub(crate) enum KeyMaterial {
    /// Generated by this operation; wiped by OpenSSL when dropped.
    Owned(RsaPrivateKey),
    /// A cached test key supplied through [`super::testing::supply_generated_key`].
    #[cfg(not(feature = "production"))]
    Supplied(&'static RsaPrivateKey),
}

impl std::fmt::Debug for KeyMaterial {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("KeyMaterial([REDACTED])")
    }
}

impl KeyMaterial {
    /// The key.
    pub(crate) fn key(&self) -> &RsaPrivateKey {
        match self {
            KeyMaterial::Owned(key) => key,
            #[cfg(not(feature = "production"))]
            KeyMaterial::Supplied(key) => key,
        }
    }
}

/// Generates an RSA key with progress and cancel (FR-16, NFR-03). In non-production
/// builds a test may have supplied a cached key of this size instead.
pub(crate) fn generate_key(
    bits: u32,
    cancel: &CancelFlag,
    progress: &dyn ProgressSink,
) -> Result<KeyMaterial, CryptoError> {
    #[cfg(not(feature = "production"))]
    if let Some(key) = super::testing::take_supplied_key(bits) {
        progress.report(Progress::KeyGeneration { work: 1 });
        if cancel.is_cancelled() {
            return Err(CryptoError::Cancelled);
        }
        return Ok(KeyMaterial::Supplied(key));
    }
    let report = |work: u64| progress.report(Progress::KeyGeneration { work });
    generate_rsa(bits, cancel, &report).map(KeyMaterial::Owned)
}

/// Reaching `point`: fails with [`OpsError::InjectedFault`] when a test armed it.
#[inline]
pub(crate) fn fault(point: FaultPoint) -> Result<(), OpsError> {
    #[cfg(not(feature = "production"))]
    if super::testing::take_fault(point) {
        return Err(OpsError::InjectedFault(format!("{point:?}")));
    }
    let _ = point;
    Ok(())
}

/// A serial candidate a test queued (checked for uniqueness like any random one).
#[inline]
pub(crate) fn serial_candidate() -> Option<Serial> {
    #[cfg(not(feature = "production"))]
    {
        super::testing::take_serial_candidate()
    }
    #[cfg(feature = "production")]
    {
        None
    }
}

/// True while a test simulates a crash: an operation that failed must not clean up.
#[inline]
pub(crate) fn simulating_crash() -> bool {
    #[cfg(not(feature = "production"))]
    {
        super::testing::crash_mode()
    }
    #[cfg(feature = "production")]
    {
        false
    }
}
